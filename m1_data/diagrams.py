"""Per-course dependency diagrams (HTML + inline SVG) and an index page.

Drawn to the diagram-design skill's rules (dependency-graph type, default
skin): ranked rows, 4px grid, orthogonal r=8 elbows, fanned attach points,
arrows painted before boxes, opaque label masks, ≤9 nodes with "+N more"
aggregation, ≤2 accent elements (the EXCLUDES edge and its label), bottom
legend strip, accessible <svg role="img"> with <title>/<desc>.

Layout of one course page (arrows point from dependent to dependency):

    UNLOCKS   [CS4246] [CS4278] [+3 more]          courses that need this one
                  \\       |       /
    COURSE         [ CS3263 ] - - EXCLUDES - - [can't take with: CS3243 ...]
                  /    |     |    \\
    REQUIRES  [any 1 of] [any 1 of] [any 1 of] [any 1 of]   prerequisite groups

Generated by `python -m m1_data build`; do not edit the HTML by hand.
"""
from __future__ import annotations

import html
import math

# ---- default skin (diagram-design references/style-guide.md) -------------
PAPER, INK, MUTED, SOFT = "#f5f5f5", "#2d3142", "#4f5d75", "#5a6580"
ACCENT, LINK = "#bf4520", "#2e5aa8"
SANS = "'Geist', system-ui, sans-serif"
MONO = "'Geist Mono', ui-monospace, monospace"
SERIF = "'Instrument Serif', serif"
FONTS = ("https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1"
         "&family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500;600&display=swap")

TREAT = {   # node type -> (fill, stroke, stroke-width, dash)
    "backend":  ("#ffffff", INK, 1, None),
    "focal":    ("#ffffff", INK, 1.6, None),          # weight, not colour: accent is reserved
    "store":    ("rgba(45,49,66,0.05)", MUTED, 0.8, None),
    "external": ("rgba(45,49,66,0.03)", "rgba(45,49,66,0.30)", 1, None),
    "optional": ("rgba(45,49,66,0.02)", "rgba(45,49,66,0.20)", 1, "4,3"),
    "input":    ("rgba(79,93,117,0.10)", SOFT, 1, None),
}

W = 960                 # doc-inline width; height is derived (fit)
X0, X1 = 112, 936       # content area (left margin holds the rank labels)
NODE_W, NODE_H = 160, 56
MAIN_W, MAIN_H = 240, 68
GROUP_W = 188
COL = 56                # code-grid column pitch inside a group box
LINE = 14               # text line pitch inside a group box
MAX_NODES = 9
EXCL_GAP = 104          # course -> exclusion box horizontal gap


def g4(v: float) -> int:
    """Snap to the 4px grid."""
    return int(round(v / 4.0) * 4)


def esc(s) -> str:
    return html.escape(str(s), quote=True)


def mono_w(s: str, size: float) -> float:
    return len(s) * size * 0.62


def sans_w(s: str, size: float) -> float:
    return len(s) * size * 0.60


def clip(s: str, width: float, size: float, mono: bool = True) -> str:
    per = size * (0.62 if mono else 0.60)
    n = int(width // per)
    return s if len(s) <= n else s[: max(1, n - 1)] + "…"


def sems(offered) -> str:
    names = {1: "S1", 2: "S2", 3: "ST1", 4: "ST2"}
    return " ".join(names.get(s, str(s)) for s in offered) or "not offered"


# ---- connectors ------------------------------------------------------------
def route(pairs, y_src: int, y_dst: int, color=MUTED, marker="arrow", bus_base: int | None = None):
    """Order-preserving fan of downward connectors with no crossings.

    pairs: [(x_src, x_dst)] sorted by x_src with x_dst in the same order.
    Left-moving edges further right take lower buses; right-moving edges
    further left take lower buses (proved crossing-free for this order).
    Returns SVG path strings.
    """
    base = y_src if bus_base is None else bus_base
    left = [i for i, (s, t) in enumerate(pairs) if t < s]
    right = [i for i, (s, t) in enumerate(pairs) if t > s]
    bus = {}
    for k, i in enumerate(left):
        bus[i] = base + 16 + 12 * k
    for k, i in enumerate(reversed(right)):
        bus[i] = base + 16 + 12 * k
    out = []
    for i, (s, t) in enumerate(pairs):
        if s == t:
            d = f"M {s},{y_src} V {y_dst}"
        else:
            y = bus[i]
            sx = 1 if t > s else -1
            d = (f"M {s},{y_src} V {y - 8} Q {s},{y} {s + 8 * sx},{y} "
                 f"H {t - 8 * sx} Q {t},{y} {t},{y + 8} V {y_dst}")
        out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="1" '
                   f'marker-end="url(#{marker})"/>')
    return out


def levels_needed(pairs) -> int:
    l = sum(1 for s, t in pairs if t < s)
    r = sum(1 for s, t in pairs if t > s)
    return max(l, r)


def attach_points(left: int, width: int, targets: list[int]) -> list[int]:
    """Distinct attach points on one box edge, ≥12px apart, snapped straight
    under a target when that target sits within the box span."""
    n = len(targets)
    pts = [g4(left + width * (k + 1) / (n + 1)) for k in range(n)]
    for k, t in enumerate(targets):
        if left + 12 <= t <= left + width - 12:
            lo = pts[k - 1] + 12 if k > 0 else left + 8
            hi = pts[k + 1] - 12 if k + 1 < n else left + width - 8
            if lo <= t <= hi:
                pts[k] = t
    for k, t in enumerate(targets):          # elbows need ≥16px of run
        if 0 < abs(pts[k] - t) < 16:
            lo = pts[k - 1] + 12 if k > 0 else left + 8
            hi = pts[k + 1] - 12 if k + 1 < n else left + width - 8
            if lo <= t <= hi:
                pts[k] = t
    return pts


# ---- nodes -----------------------------------------------------------------
def tag(x, y, text) -> str:
    w = g4(len(text) * 4.9 + 10)
    return (f'<rect x="{x}" y="{y}" width="{w}" height="12" rx="2" fill="transparent" '
            f'stroke="rgba(45,49,66,0.40)" stroke-width="0.8"/>'
            f'<text x="{x + w / 2:g}" y="{y + 9}" fill="{INK}" font-size="7" font-family="{MONO}" '
            f'text-anchor="middle" letter-spacing="0.08em">{esc(text)}</text>')


def badge(x_right, y, text) -> str:
    w = max(28, g4(len(text) * 5.2 + 8))
    x = x_right - w
    return (f'<rect x="{x}" y="{y}" width="{w}" height="12" rx="2" fill="transparent" '
            f'stroke="rgba(45,49,66,0.40)" stroke-width="0.8"/>'
            f'<text x="{x + w / 2:g}" y="{y + 9}" fill="{INK}" font-size="8" font-family="{MONO}" '
            f'text-anchor="middle">{esc(text)}</text>')


def box(x, y, w, h, kind) -> str:
    fill, stroke, sw, dash = TREAT[kind]
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{PAPER}"/>'
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{sw}"{d}/>')


def course_node(x, y, c, fan_in, href, kind="backend", w=NODE_W, h=NODE_H, label="COURSE",
                sub=None, sub2=None) -> str:
    cx = x + w / 2
    parts = [box(x, y, w, h, kind), tag(x + 8, y + 6, label)]
    if fan_in is not None:
        parts.append(badge(x + w - 8, y + 8, f"{fan_in} IN"))
    name_y = y + (28 if sub2 is None else 30)
    parts.append(f'<text x="{cx:g}" y="{name_y}" fill="{INK}" font-size="12" font-weight="600" '
                 f'font-family="{SANS}" text-anchor="middle">{esc(c)}</text>')
    if sub:
        parts.append(f'<text x="{cx:g}" y="{name_y + 16}" fill="{MUTED}" font-size="9" '
                     f'font-family="{MONO}" text-anchor="middle">{esc(clip(sub, w - 16, 9))}</text>')
    if sub2:
        parts.append(f'<text x="{cx:g}" y="{name_y + 30}" fill="{SOFT}" font-size="9" '
                     f'font-family="{MONO}" text-anchor="middle">{esc(clip(sub2, w - 16, 9))}</text>')
    g = "".join(parts)
    return f'<a href="{href}">{g}</a>' if href else g


class Ctx:
    def __init__(self, catalog, fan_in, pages):
        self.cs = catalog["courses"]
        self.fan_in = fan_in
        self.pages = pages            # codes that get their own page

    def href(self, code):
        return f"{code}.html" if code in self.pages else None

    def plannable(self, code):
        c = self.cs.get(code)
        return bool(c and c["exists_in_ay"] and c["available"])

    def state(self, code) -> str:
        """ok | out_of_scope (exists, not fetched) | closed (retired, not offered, not open)."""
        c = self.cs.get(code)
        if self.plannable(code):
            return "ok"
        if c and c["exists_in_ay"] and c["details"] == "stub":
            return "out_of_scope"
        return "closed"


# ---- requirement groups ----------------------------------------------------
def compact(n) -> str:
    if n["op"] == "course":
        return n["code"]
    inner = [compact(a) for a in n["args"]]
    if n["op"] == "and":
        return " + ".join(inner)
    k = 1 if n["op"] == "or" else n["n"]
    return f"{k} of {{{', '.join(inner)}}}"


def wrap(text: str, width_chars: int) -> list[str]:
    words, lines, cur = text.split(" "), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width_chars:
            lines.append(cur)
            cur = "  " + w
        else:
            cur = f"{cur} {w}" if cur else w
    if cur:
        lines.append(cur)
    return lines


def group_spec(node, ctx: Ctx):
    """Describe one requirement group: (kind, label, payload, height)."""
    if node["op"] == "course":
        return ("course", None, node["code"], NODE_H)
    label = "ANY 1 OF" if node["op"] == "or" else (
        f"{node['n']} OF" if node["op"] == "n_of" else "ALL OF")
    if all(a["op"] == "course" for a in node["args"]):
        codes = [a["code"] for a in node["args"]]
        shown = codes if len(codes) <= 12 else codes[:11]
        rows = math.ceil(len(shown) / 3) + (1 if len(codes) > len(shown) else 0)
        return ("grid", label, (shown, len(codes) - len(shown)), 28 + rows * LINE + 8)
    chars = int((GROUP_W - 24) // (9 * 0.62))
    lines = []
    for a in node["args"]:
        for i, ln in enumerate(wrap(compact(a), chars - 2)):
            lines.append(("• " if i == 0 else "  ") + ln.lstrip())
    more = 0
    if len(lines) > 10:
        more, lines = len(lines) - 9, lines[:9] + ["  … (see text below)"]
    return ("lines", label, lines, 28 + len(lines) * LINE + 8)


def draw_group(x, y, spec, ctx: Ctx) -> str:
    kind, label, payload, h = spec
    if kind == "course":
        code = payload
        c = ctx.cs.get(code, {})
        k = "backend" if ctx.plannable(code) else "external"
        return course_node(x + (GROUP_W - NODE_W) // 2, y, code, ctx.fan_in.get(code), ctx.href(code), k,
                           sub=c.get("title") or ("not offered" if not c.get("exists_in_ay") else ""))
    parts = [box(x, y, GROUP_W, h, "store"), tag(x + 8, y + 6, label)]
    if kind == "grid":
        codes, more = payload
        for i, code in enumerate(codes):
            tx = x + 12 + (i % 3) * COL
            ty = y + 32 + (i // 3) * LINE
            st = ctx.state(code)
            deco = ' text-decoration="line-through"' if st == "closed" else ""
            fill = INK if st == "ok" else SOFT
            t = (f'<text x="{tx}" y="{ty}" fill="{fill}" font-size="9" font-family="{MONO}"{deco}>'
                 f'{esc(code)}</text>')
            href = ctx.href(code)
            parts.append(f'<a href="{href}">{t}</a>' if href else t)
        if more:
            ty = y + 32 + math.ceil(len(codes) / 3) * LINE
            parts.append(f'<text x="{x + 12}" y="{ty}" fill="{SOFT}" font-size="9" '
                         f'font-family="{MONO}">+{more} more</text>')
    else:
        for i, ln in enumerate(payload):
            parts.append(f'<text x="{x + 12}" y="{y + 32 + i * LINE}" fill="{INK}" font-size="9" '
                         f'font-family="{MONO}" xml:space="preserve">{esc(ln)}</text>')
    return "".join(parts)


# ---- one course ------------------------------------------------------------
def course_svg(code: str, ctx: Ctx) -> tuple[str, int, dict]:
    c = ctx.cs[code]
    slug = code.lower()
    logic = c["prereq"]["logic"]

    # Requirement groups (bottom row).
    if logic is None:
        groups = [("note", "NO PREREQUISITE", ["Nothing required", "for this student"], 28 + 2 * LINE + 8)]
    elif logic is False:
        groups = [("note", "NEVER MET", ["Closed to this student:", *[r[:30] for r in c["unavailable_reasons"][:2]]],
                   28 + 3 * LINE + 8)]
    else:
        args = logic["args"] if logic["op"] == "and" else [logic]
        groups = [group_spec(a, ctx) for a in args]

    excl = c["preclusion"]["mutually_exclusive_with"]
    excl_nodes = 1 if excl else 0
    max_groups = 4
    hidden_groups = 0
    if len(groups) > max_groups:
        hidden_groups = len(groups) - (max_groups - 1)
        groups = groups[: max_groups - 1] + [("note", "MORE", [f"+{hidden_groups} more", "requirements"],
                                              28 + 2 * LINE + 8)]

    unl = sorted(c["unlocks"], key=lambda u: (not ctx.plannable(u), -ctx.fan_in.get(u, 0), u))
    slots = min(4, MAX_NODES - 1 - excl_nodes - len(groups))
    if len(unl) > slots:
        shown_unl, more_unl = unl[: max(slots - 1, 0)], len(unl) - max(slots - 1, 0)
    else:
        shown_unl, more_unl = unl, 0

    # ---- geometry ----
    y = 56
    rank_labels = []
    up_nodes = []                     # (x, code or None)
    n_up = len(shown_unl) + (1 if more_unl else 0)
    main_x = g4(X0 + (X1 - X0 - (MAIN_W + (EXCL_GAP + 200 if excl else 0))) / 2)
    main_cx = main_x + MAIN_W // 2

    if n_up:
        pitch = NODE_W + 24
        span = n_up * NODE_W + (n_up - 1) * 24
        ux = g4(main_cx - span / 2)
        ux = max(X0, min(ux, X1 - span))
        for i in range(n_up):
            up_nodes.append((ux + i * pitch, shown_unl[i] if i < len(shown_unl) else None))
        rank_labels.append(("NEEDED BY", y))
        up_y = y
        y += NODE_H
        up_targets = [x + NODE_W // 2 for x, _ in up_nodes]
        a_top = attach_points(main_x, MAIN_W, up_targets)
        pairs_up = list(zip(up_targets, a_top))
        y += max(64, 40 + 12 * levels_needed(pairs_up))
    main_y = y

    # exclusion box
    ex_lines = []
    if excl:
        shown = excl[:15]
        ex_lines = [shown[i:i + 3] for i in range(0, len(shown), 3)]
        ex_more = len(excl) - len(shown)
        ex_h = 28 + (len(ex_lines) + (1 if ex_more else 0)) * LINE + 8
        ex_w = 200
        ex_x = main_x + MAIN_W + EXCL_GAP
        ex_y = g4(main_y + MAIN_H / 2 - ex_h / 2)
        row_top = min(main_y, ex_y)
        if row_top < main_y:          # keep the box clear of the buses above
            shift = main_y - row_top
            main_y += shift
            ex_y += shift
            y += shift
        row_bottom = max(main_y + MAIN_H, ex_y + ex_h)
    else:
        row_bottom = main_y + MAIN_H
    rank_labels.append(("COURSE", main_y))

    # groups row
    n_g = len(groups)
    span = n_g * GROUP_W + (n_g - 1) * 24
    gx = g4(main_cx - span / 2)
    gx = max(X0, min(gx, X1 - span))
    g_xs = [gx + i * (GROUP_W + 24) for i in range(n_g)]
    g_targets = [x + GROUP_W // 2 for x in g_xs]
    a_bot = attach_points(main_x, MAIN_W, g_targets)
    pairs_dn = list(zip(a_bot, g_targets))
    # Buses run below the whole course row (the exclusion box may hang lower
    # than the course), so no horizontal segment passes behind the box.
    bus_base = row_bottom
    lv = levels_needed(pairs_dn)
    g_y = g4(max(main_y + MAIN_H + 64, bus_base + 16 + 12 * max(lv - 1, 0) + 40))
    rank_labels.append(("REQUIRES", g_y))
    g_bottom = g_y + max(s[3] for s in groups)

    legend_y = g_bottom + 36
    height = g4(legend_y + 64)

    # ---- paint: connectors first ----
    svg = []
    for label, ly in rank_labels:
        svg.append(f'<text x="24" y="{ly + 12}" fill="{MUTED}" font-size="8" font-family="{MONO}" '
                   f'letter-spacing="0.18em">{label}</text>')
    if n_up:
        svg += route(pairs_up, up_y + NODE_H, main_y)
    svg += route(pairs_dn, main_y + MAIN_H, g_y, bus_base=bus_base)
    if excl:
        ly = main_y + MAIN_H // 2
        x1, x2 = main_x + MAIN_W, ex_x
        svg.append(f'<line x1="{x1}" y1="{ly}" x2="{x2}" y2="{ly}" stroke="{ACCENT}" stroke-width="1.2" '
                   f'stroke-dasharray="5,4" marker-end="url(#arrow-accent)"/>')
        mid = (x1 + x2) // 2
        svg.append(f'<rect x="{mid - 26}" y="{ly - 20}" width="52" height="12" rx="2" fill="{PAPER}"/>'
                   f'<text x="{mid}" y="{ly - 11}" fill="{ACCENT}" font-size="8" font-family="{MONO}" '
                   f'text-anchor="middle" letter-spacing="0.06em">EXCLUDES</text>')

    # ---- nodes ----
    for x, u in up_nodes:
        if u is None:
            svg.append(course_node(x, up_y, f"+{more_unl} more", None, "#unlocks", "external",
                                   label="MORE", sub="full list below"))
        else:
            k = "backend" if ctx.plannable(u) else "external"
            svg.append(course_node(x, up_y, u, ctx.fan_in.get(u), ctx.href(u), k,
                                   sub=ctx.cs[u]["title"] or ""))
    main_kind = "focal" if c["available"] and c["exists_in_ay"] else "external"
    svg.append(course_node(main_x, main_y, code, ctx.fan_in.get(code), None, main_kind,
                           w=MAIN_W, h=MAIN_H, label="THIS COURSE", sub=c["title"] or "",
                           sub2=f"{c['mc']} MC · {sems(c['offered'])}"
                           + ("" if c["available"] else " · not plannable")))
    if excl:
        parts = [box(ex_x, ex_y, ex_w, ex_h, "optional"), tag(ex_x + 8, ex_y + 6, "CAN'T TAKE WITH")]
        for r, row in enumerate(ex_lines):
            for k, xc in enumerate(row):
                t = (f'<text x="{ex_x + 12 + k * 60}" y="{ex_y + 32 + r * LINE}" fill="{INK}" font-size="9" '
                     f'font-family="{MONO}">{esc(xc)}</text>')
                h = ctx.href(xc)
                parts.append(f'<a href="{h}">{t}</a>' if h else t)
        if ex_more:
            parts.append(f'<text x="{ex_x + 12}" y="{ex_y + 32 + len(ex_lines) * LINE}" fill="{SOFT}" '
                         f'font-size="9" font-family="{MONO}">+{ex_more} more</text>')
        svg.append("".join(parts))
    for x, spec in zip(g_xs, groups):
        if spec[0] == "note":
            _, label, lines, h = spec
            parts = [box(x, g_y, GROUP_W, h, "store"), tag(x + 8, g_y + 6, label)]
            for i, ln in enumerate(lines):
                parts.append(f'<text x="{x + 12}" y="{g_y + 32 + i * LINE}" fill="{INK}" font-size="9" '
                             f'font-family="{MONO}">{esc(ln)}</text>')
            svg.append("".join(parts))
        else:
            svg.append(draw_group(x, g_y, spec, ctx))

    # ---- legend strip ----
    ly = legend_y
    leg = [f'<line x1="24" y1="{ly}" x2="{W - 24}" y2="{ly}" stroke="rgba(45,49,66,0.10)" stroke-width="0.8"/>',
           f'<text x="24" y="{ly + 16}" fill="{MUTED}" font-size="8" font-family="{MONO}" '
           f'letter-spacing="0.18em">LEGEND</text>']
    items = [
        ("box", "backend", "Course (click to open)"),
        ("box", "store", "Requirement group"),
        ("box", "external", "Not plannable here"),
        ("line", None, "Mutually exclusive"),
        ("text", None, "N IN = courses that need it"),
    ]
    lx = 24
    for kind, tr, text in items:
        if kind == "box":
            fill, stroke, sw, _ = TREAT[tr]
            leg.append(f'<rect x="{lx}" y="{ly + 28}" width="16" height="12" rx="2" fill="{fill}" '
                       f'stroke="{stroke}" stroke-width="{sw}"/>')
            tx = lx + 24
        elif kind == "line":
            leg.append(f'<line x1="{lx}" y1="{ly + 34}" x2="{lx + 20}" y2="{ly + 34}" stroke="{ACCENT}" '
                       f'stroke-width="1.2" stroke-dasharray="5,4"/>')
            tx = lx + 28
        else:
            tx = lx
        leg.append(f'<text x="{tx}" y="{ly + 37}" fill="{MUTED}" font-size="8.5" font-family="{SANS}">'
                   f'{esc(text)}</text>')
        lx = g4(tx + sans_w(text, 8.5) + 28)
    leg.append(f'<text x="24" y="{ly + 56}" fill="{MUTED}" font-size="8.5" font-family="{SANS}">'
               f'Struck through = cannot be planned this AY (closed to this student, not offered, or retired). Grey = outside the fetched scope. Arrows point to what a course needs.</text>')
    svg += leg

    n_req = len(c["prereq"]["courses"])
    desc = (f"{code} {c['title']}: needs {c['prereq']['text'] if logic else 'no prerequisite'}; "
            f"needed by {len(c['unlocks'])} course(s); mutually exclusive with "
            f"{', '.join(excl) if excl else 'none'}.")
    head = (f'<svg viewBox="0 0 {W} {height}" xmlns="http://www.w3.org/2000/svg" role="img" '
            f'aria-labelledby="{slug}-title {slug}-desc">'
            f'<title id="{slug}-title">{esc(code)}: prerequisites and dependents</title>'
            f'<desc id="{slug}-desc">{esc(desc)}</desc>'
            '<defs>'
            f'<marker id="arrow" markerWidth="8" markerHeight="6" refX="7" refY="3" orient="auto">'
            f'<polygon points="0 0, 8 3, 0 6" fill="{MUTED}"/></marker>'
            f'<marker id="arrow-accent" markerWidth="8" markerHeight="6" refX="7" refY="3" orient="auto">'
            f'<polygon points="0 0, 8 3, 0 6" fill="{ACCENT}"/></marker>'
            '</defs>'
            f'<rect width="100%" height="100%" fill="{PAPER}"/>')
    info = {"unlocks_hidden": more_unl, "groups_hidden": hidden_groups, "n_req": n_req}
    return head + "\n".join(svg) + "</svg>", height, info


