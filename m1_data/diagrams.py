def page(title: str, eyebrow: str, body: str) -> str:
    return ("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"UTF-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n"
            f"<title>{esc(title)}</title>\n<link href=\"{FONTS}\" rel=\"stylesheet\">\n"
            f"<style>{CSS}</style>\n</head>\n<body>\n<div class=\"frame\">\n"
            f"<p class=\"eyebrow\">{eyebrow}</p>\n{body}\n</div>\n</body>\n</html>\n")


def links(codes, ctx: Ctx) -> str:
    if not codes:
        return '<span class="muted">none</span>'
    out = []
    for x in codes:
        h = ctx.href(x)
        out.append(f'<a class="mono" href="{h}">{x}</a>' if h else f'<span class="mono muted">{x}</span>')
    return ", ".join(out)


def course_page(code, ctx: Ctx, ay: str) -> str:
    c = ctx.cs[code]
    svg, _, _ = course_svg(code, ctx)
    rows = [
        ("Prerequisite", f'<span class="mono">{esc(c["prereq"]["text"])}</span>'),
        ("Corequisite", f'<span class="mono">{esc(c["coreq"]["text"])}</span>') if c["coreq"]["logic"] else None,
        ("Blocked if completed", f'<span class="mono">{esc(c["preclusion"]["text"])}</span>'),
        ("Mutually exclusive", links(c["preclusion"]["mutually_exclusive_with"], ctx)),
        (f'<span id="unlocks">Needed by ({len(c["unlocks"])})</span>', links(c["unlocks"], ctx)),
        ("Offered", f'{sems(c["offered"])} · {c["mc"]} MC'),
        ("Plannable", "yes" if c["available"] else "no: " + esc("; ".join(c["unavailable_reasons"]))),
        ("Assumed", "<br>".join(esc(a) for a in c["assumptions"])) if c["assumptions"] else None,
        ("Parser warnings", "<br>".join(esc(w) for w in c["warnings"])) if c["warnings"] else None,
        ("NUSMods text", esc(c["prereq"]["source_text"] or "—")),
        ("Source", f'<span class="mono">nusmods.com/courses/{code}</span> (fetched data, AY{ay})'),
    ]
    dl = "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in (r for r in rows if r))
    body = (f"<h1>{esc(code)} · {esc(c['title'])}</h1>\n"
            f"<div class=\"diagram-container\">{svg}</div>\n"
            f"<h2>Details</h2><dl>{dl}</dl>")
    return page(f"{code} prerequisites", f'Dependency graph · AY{ay} · <a href="index.html">all courses</a>', body)


def index_page(ctx: Ctx, graph: dict, ay: str) -> str:
    nodes = {n["id"]: n for n in graph["nodes"] if n["kind"] == "course"}
    rows = []
    for code in sorted(ctx.pages):
        c, n = ctx.cs[code], nodes[code]
        rows.append(f'<tr data-k="{esc((code + " " + (c["title"] or "")).lower())}">'
                    f'<td><a class="mono" href="{code}.html">{code}</a></td><td>{esc(c["title"])}</td>'
                    f'<td class="num">{c["mc"]}</td><td class="mono">{sems(c["offered"])}</td>'
                    f'<td class="num">{n["fan_in"]}</td><td class="num">{n["depth"]}</td>'
                    f'<td>{"" if c["available"] else "<span class=muted>no</span>"}</td></tr>')
    body = (
        f"<h1>Course graph, AY{ay}</h1>\n"
        "<div class=\"overviews\">"
        "<a href=\"../../../../docs/diagrams/cs-core-chain.html\"><b>BComp CS core chain</b>"
        "<span>How the first-year courses feed CS3263</span></a>"
        "<a href=\"../../../../docs/diagrams/exclusion-trap.html\"><b>The CS3244 trap</b>"
        "<span>Why one course can make CS3263 impossible</span></a>"
        "<a href=\"../graph.json\"><b>graph.json</b>"
        "<span>The same graph as nodes and edges, for code</span></a></div>\n"
        "<input id=\"q\" type=\"search\" placeholder=\"Filter by code or title…\" "
        "aria-label=\"Filter courses\">\n"
        "<div style=\"overflow-x:auto\"><table><thead><tr><th>Course</th><th>Title</th><th>MC</th>"
        "<th>Offered</th><th title=\"courses that need it\">Needed by</th>"
        "<th title=\"longest prerequisite chain below it\">Depth</th><th>Plannable</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>\n"
        "<script>const q=document.getElementById('q');q.addEventListener('input',()=>{const v=q.value"
        ".toLowerCase();document.querySelectorAll('tbody tr').forEach(r=>{r.style.display=r.dataset.k"
        ".includes(v)?'':'none'})});</script>")
    return page(f"Course graph AY{ay}", "Dependency graphs · generated by m1_data", body)


def write_diagrams(out_dir, catalog: dict, graph: dict) -> int:
    out_dir.mkdir(parents=True, exist_ok=True)
    fan_in = {n["id"]: n["fan_in"] for n in graph["nodes"] if n["kind"] == "course"}
    pages = {code for code, c in catalog["courses"].items() if c["details"] == "full"}
    ctx = Ctx(catalog, fan_in, pages)
    ay = catalog["acad_year"]
    for old in out_dir.glob("*.html"):
        if old.stem not in pages and old.name != "index.html":
            old.unlink()
    for code in sorted(pages):
        (out_dir / f"{code}.html").write_text(course_page(code, ctx, ay), encoding="utf-8", newline="\n")
    (out_dir / "index.html").write_text(index_page(ctx, graph, ay), encoding="utf-8", newline="\n")
    print(f"[diagrams] {len(pages)} course pages + index -> {out_dir}")
    return len(pages)
